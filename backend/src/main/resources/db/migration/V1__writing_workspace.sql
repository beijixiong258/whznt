CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone varchar(11) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES account(id),
    kind varchar(12) NOT NULL CHECK (kind IN ('WRITING', 'CHAT')),
    title varchar(120) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX conversation_owner_recent_idx ON conversation (owner_id, updated_at DESC, id DESC);

CREATE TABLE chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversation(id),
    role varchar(12) NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX chat_message_conversation_idx ON chat_message (conversation_id, id);

CREATE TABLE draft (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL UNIQUE REFERENCES conversation(id),
    current_version_id bigint
);

CREATE TABLE draft_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id bigint NOT NULL REFERENCES draft(id),
    base_version_id bigint REFERENCES draft_version(id),
    title varchar(120) NOT NULL,
    content text NOT NULL,
    source varchar(12) NOT NULL CHECK (source IN ('GENERATED', 'EDITED')),
    writing_input text,
    model varchar(200),
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE draft ADD CONSTRAINT draft_current_version_fk
    FOREIGN KEY (current_version_id) REFERENCES draft_version(id);

CREATE INDEX draft_version_draft_idx ON draft_version (draft_id, id DESC);

CREATE TABLE generation_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES account(id),
    request_key varchar(36) NOT NULL,
    conversation_id bigint REFERENCES conversation(id),
    kind varchar(12) NOT NULL CHECK (kind IN ('WRITE', 'REGENERATE', 'CHAT')),
    state varchar(12) NOT NULL CHECK (state IN ('RUNNING', 'COMPLETED', 'FAILED')),
    input_snapshot text NOT NULL,
    version_id bigint REFERENCES draft_version(id),
    started_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (owner_id, request_key)
);

CREATE UNIQUE INDEX generation_running_conversation_idx
    ON generation_run (conversation_id) WHERE state = 'RUNNING';
