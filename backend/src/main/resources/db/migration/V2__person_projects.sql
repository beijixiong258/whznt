CREATE TABLE person_project (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES account(id),
    name varchar(120) NOT NULL,
    summary text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX person_project_owner_idx ON person_project (owner_id, updated_at DESC, id DESC);

ALTER TABLE conversation ADD COLUMN project_id bigint REFERENCES person_project(id);
CREATE INDEX conversation_project_idx ON conversation (project_id);

CREATE TABLE project_material (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES person_project(id),
    name varchar(120) NOT NULL,
    kind varchar(12) NOT NULL CHECK (kind IN ('LIFE', 'BUSINESS', 'OBSERVATION', 'STYLE')),
    current_version_id bigint
);

CREATE TABLE material_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id bigint NOT NULL REFERENCES project_material(id),
    filename varchar(255) NOT NULL,
    storage_key varchar(64) NOT NULL UNIQUE,
    content_type varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE project_material ADD CONSTRAINT material_current_version_fk
    FOREIGN KEY (current_version_id) REFERENCES material_version(id);
CREATE INDEX project_material_project_idx ON project_material (project_id, id);
CREATE INDEX material_version_material_idx ON material_version (material_id, id DESC);

CREATE TABLE material_passage (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id bigint NOT NULL REFERENCES material_version(id),
    ordinal integer NOT NULL CHECK (ordinal > 0),
    location varchar(40) NOT NULL,
    content text NOT NULL,
    UNIQUE (version_id, ordinal)
);

CREATE TABLE project_artifact (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES person_project(id),
    conversation_id bigint NOT NULL UNIQUE REFERENCES conversation(id),
    step varchar(12) NOT NULL CHECK (step IN ('TRAITS', 'STORY', 'POSITION', 'TOPICS', 'SCRIPT')),
    slot varchar(80) NOT NULL,
    topic varchar(300) NOT NULL DEFAULT '',
    UNIQUE (project_id, step, slot)
);

CREATE TABLE project_version_context (
    id bigint PRIMARY KEY REFERENCES draft_version(id),
    project_id bigint NOT NULL REFERENCES person_project(id),
    snapshot text NOT NULL
);

CREATE TABLE project_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES person_project(id),
    request_key varchar(36) NOT NULL,
    step varchar(12) NOT NULL CHECK (step IN ('TRAITS', 'STORY', 'POSITION', 'TOPICS', 'SCRIPT')),
    slot varchar(80) NOT NULL,
    input_snapshot text NOT NULL,
    state varchar(12) NOT NULL CHECK (state IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED')),
    error text,
    conversation_id bigint REFERENCES conversation(id),
    result_version_id bigint REFERENCES draft_version(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, request_key)
);
CREATE UNIQUE INDEX project_job_active_slot_idx ON project_job (project_id, step, slot)
    WHERE state IN ('QUEUED', 'RUNNING');
CREATE INDEX project_job_schedule_idx ON project_job (state, id);
