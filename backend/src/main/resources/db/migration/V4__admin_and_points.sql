ALTER TABLE account
    ADD COLUMN role varchar(8) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    ADD COLUMN enabled boolean NOT NULL DEFAULT true,
    ADD COLUMN auth_version integer NOT NULL DEFAULT 0,
    ADD COLUMN points integer NOT NULL DEFAULT 0 CHECK (points >= 0);

ALTER TABLE recharge_order
    ADD COLUMN state varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'CREDITED', 'REJECTED')),
    ADD COLUMN credited_points integer CHECK (credited_points > 0),
    ADD COLUMN reviewed_by bigint REFERENCES account (id),
    ADD COLUMN reviewed_at timestamptz,
    ADD COLUMN review_note varchar(200) NOT NULL DEFAULT '',
    ADD CONSTRAINT recharge_review_consistency CHECK (
        (state = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND credited_points IS NULL)
        OR (state = 'CREDITED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND credited_points IS NOT NULL)
        OR (state = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND credited_points IS NULL)
    );

CREATE INDEX recharge_order_state_idx ON recharge_order (state, id DESC);

CREATE TABLE point_credit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES account (id),
    operator_id bigint NOT NULL REFERENCES account (id),
    request_id varchar(36),
    recharge_order_id bigint UNIQUE REFERENCES recharge_order (id),
    points integer NOT NULL CHECK (points > 0),
    balance_after integer NOT NULL CHECK (balance_after >= points),
    note varchar(200) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((request_id IS NULL) <> (recharge_order_id IS NULL)),
    UNIQUE (account_id, request_id)
);

CREATE INDEX point_credit_account_idx ON point_credit (account_id, id DESC);
