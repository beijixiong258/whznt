CREATE TABLE subtitle_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES account (id),
    source_key varchar(36) NOT NULL,
    source_name varchar(255) NOT NULL,
    duration_ms bigint NOT NULL CHECK (duration_ms > 0),
    mode varchar(12) NOT NULL CHECK (mode IN ('AUTO', 'ALIGN', 'IMPORT')),
    draft_version_id bigint REFERENCES draft_version (id),
    reference_title varchar(255) NOT NULL,
    reference_text text NOT NULL,
    state varchar(12) NOT NULL CHECK (state IN ('QUEUED', 'RUNNING', 'READY', 'FAILED')),
    error text NOT NULL,
    original_timeline text NOT NULL,
    timeline text NOT NULL,
    version integer NOT NULL CHECK (version >= 0),
    export_state varchar(12) NOT NULL CHECK (export_state IN ('NONE', 'QUEUED', 'RUNNING', 'READY', 'FAILED')),
    export_error text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX subtitle_task_owner_idx ON subtitle_task (owner_id, id DESC);
CREATE INDEX subtitle_task_pending_idx ON subtitle_task (updated_at, id)
    WHERE state = 'QUEUED' OR export_state = 'QUEUED';

CREATE TABLE recharge_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES account (id),
    request_key varchar(36) NOT NULL,
    request_number varchar(35) NOT NULL UNIQUE,
    amount numeric(10, 2) NOT NULL CHECK (amount > 0),
    note varchar(300) NOT NULL,
    receipt_key varchar(36) NOT NULL,
    receipt_sha256 char(64) NOT NULL,
    receipt_type varchar(20) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (owner_id, request_key),
    UNIQUE (owner_id, receipt_sha256)
);

CREATE INDEX recharge_order_owner_idx ON recharge_order (owner_id, id DESC);
